-- ── video_entries ─────────────────────────────────────────────
-- One row per daily video journal entry.
-- audio_url stores the audio-only track sent to Whisper for transcription.
-- transcript is populated asynchronously by a backend Edge Function.
CREATE TABLE IF NOT EXISTS video_entries (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id       uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  entry_date    date NOT NULL,                   -- local calendar date of the entry
  rating        smallint NOT NULL CHECK (rating BETWEEN 1 AND 10),
  video_url     text NOT NULL,                   -- Supabase Storage public URL
  audio_url     text,                            -- audio-only track for Whisper
  thumbnail_url text,                            -- frozen final frame JPEG
  transcript    text,                            -- populated by transcription Edge Function
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- Prevent duplicate entries for the same user on the same day
CREATE UNIQUE INDEX IF NOT EXISTS video_entries_user_date
  ON video_entries (user_id, entry_date);

-- RLS
ALTER TABLE video_entries ENABLE ROW LEVEL SECURITY;

-- Users can read their own entries
CREATE POLICY "Own entries: read"
  ON video_entries FOR SELECT
  USING (auth.uid() = user_id);

-- Friends can read each other's entries
CREATE POLICY "Friend entries: read"
  ON video_entries FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM friendships
      WHERE status = 'accepted'
        AND (
          (requester_id = auth.uid() AND addressee_id = video_entries.user_id)
          OR
          (addressee_id = auth.uid() AND requester_id = video_entries.user_id)
        )
    )
  );

-- Users can insert their own entries
CREATE POLICY "Own entries: insert"
  ON video_entries FOR INSERT
  WITH CHECK (auth.uid() = user_id);

-- Users can update their own entries (e.g. transcript backfill)
CREATE POLICY "Own entries: update"
  ON video_entries FOR UPDATE
  USING (auth.uid() = user_id);


-- ── monthly_newsletters ───────────────────────────────────────
-- One row per user per calendar month, generated by AI Edge Function.
CREATE TABLE IF NOT EXISTS monthly_newsletters (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id       uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  period_month  date NOT NULL,   -- first day of the month, e.g. 2026-03-01
  content       text NOT NULL,   -- full text of the AI-generated review
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, period_month)
);

ALTER TABLE monthly_newsletters ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Own newsletters: read"
  ON monthly_newsletters FOR SELECT
  USING (auth.uid() = user_id);

CREATE POLICY "Own newsletters: insert"
  ON monthly_newsletters FOR INSERT
  WITH CHECK (auth.uid() = user_id);


